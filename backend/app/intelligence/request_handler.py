"""IntelligentRequestHandler — the single entry point for Noor AI inference.

Composes the intelligence layer for one user message:
    cache probe → (on miss) memory retrieval → prompt assembly with memory
    injection → optional history compression → gateway generation → honest
    savings accounting.

Synchronous by design (the "synchronous first, SSE later" decision). It returns
a fully-formed answer plus a HandlerResult carrying the savings metadata that
the route layer turns into x-noor-* response headers.

Separation of concerns: this handler *composes* TokenReducer's individual levels
(cache probe, compression) rather than calling ``TokenReducer.reduce`` — because
the real request path injects memory into the system prompt and keeps the recent
raw turns, a nuanced strategy distinct from reduce()'s standalone history-swap.
Persisting messages and scheduling background memory processing belong to the
route, not here.
"""
from __future__ import annotations

from backend.app.textfix import repair_mojibake

import logging
import uuid
from typing import Optional

from backend.app import providers
from backend.app.gems import GEMS
from backend.app.intelligence import gateway_chat, profile_store
from backend.app.intelligence.memory import MemoryProcessor
from backend.app.intelligence.models import HandlerResult
from backend.app.intelligence.token_reducer import TokenReducer
from backend.app.settings import NOOR_COST_PER_TOKEN_USD

logger = logging.getLogger("noor.intelligence.request_handler")


class IntelligentRequestHandler:
    def __init__(
        self,
        memory_processor: Optional[MemoryProcessor] = None,
        token_reducer: Optional[TokenReducer] = None,
    ):
        self.memory = memory_processor or MemoryProcessor()
        self.reducer = token_reducer or TokenReducer(self.memory)

    def handle_message(
        self,
        user_id: str,
        conversation_id: str,
        messages: list[dict],
        gem_id: str = "general",
        stream: bool = False,  # accepted for API parity; SSE is a later phase
    ) -> HandlerResult:
        base_prompt = (GEMS.get(gem_id) or GEMS["general"])["system_prompt"]
        last_user = next(
            (m.get("content", "") for m in reversed(messages) if m.get("role") == "user"),
            messages[-1].get("content", "") if messages else "",
        )

        # Baseline = what a naive client (no intelligence layer) would have sent:
        # the plain system prompt + the entire raw history. All savings are
        # measured honestly against this, and never allowed to go negative.
        baseline_tokens = self.reducer.estimate_tokens(
            [{"role": "system", "content": base_prompt}, *messages]
        )

        levels_applied: list[str] = []

        # A user-supplied key bypasses Noor's semantic cache on purpose: that
        # cache is keyed to Noor's model routes, and answering from it would
        # hand a Claude request an answer generated by a different model.
        route = providers.current_route()
        byok_provider = route.provider if route is not None else None

        # 1) CACHE PROBE (cheapest). On hit we pay nothing for generation.
        cache = (
            {"hit": False, "cached_response": None}
            if byok_provider
            else self.reducer.level1_cache_hit(last_user)
        )
        if cache["hit"] and cache.get("cached_response"):
            return self._finish(
                content=repair_mojibake(cache["cached_response"]),
                user_id=user_id,
                conversation_id=conversation_id,
                cache_hit=True,
                memories_used=0,
                tokens_saved=baseline_tokens,     # sent 0 tokens to the model
                model_used="noor-cache",
                levels_applied=["level1_cache_hit"],
            )


        # 2) MEMORY RETRIEVAL (only needed on a cache miss).
        ctx = self.memory.retrieve_relevant_memories(user_id, last_user)
        injection = self.memory.build_memory_injection(ctx)
        if injection:
            levels_applied.append("memory_injection")
        system_content = base_prompt + (f"\n\n{injection}" if injection else "")

        # 3) CONTEXT COMPRESSION (only when the conversation is genuinely large).
        history = messages
        if self.reducer.should_compress(messages):
            compressed = self.reducer.level3_history_compression(messages)
            if compressed is not messages:
                history = compressed
                levels_applied.append("level3_history_compression")

        # 4) PROMPT ASSEMBLY.
        assembled = [{"role": "system", "content": system_content}, *history]
        if self.reducer.estimate_tokens(assembled) > 4000:
            assembled = self.reducer.level4_smart_truncation(assembled)
            levels_applied.append("level4_smart_truncation")

        # 5) GATEWAY CALL. A generation failure here IS fatal (unlike memory).
        try:
            reply = gateway_chat.chat(assembled)
        except gateway_chat.GatewayError as error:
            raise providers.GenerationError(
                f"Generation failed: {error}", status=getattr(error, "status", 502)
            ) from error

        # 6) HONEST SAVINGS: naive baseline minus what we actually sent as prompt.
        actual_prompt_tokens = reply.prompt_tokens
        tokens_saved = max(0, baseline_tokens - actual_prompt_tokens)

        return self._finish(
            content=repair_mojibake(reply.content),
            user_id=user_id,
            conversation_id=conversation_id,
            cache_hit=reply.cache_hit,
            memories_used=ctx.memory_count,
            tokens_saved=tokens_saved,
            model_used=reply.model_used,
            levels_applied=levels_applied,
            byok_provider=byok_provider,
        )

    def _finish(
        self,
        *,
        content: str,
        user_id: str,
        conversation_id: str,
        cache_hit: bool,
        memories_used: int,
        tokens_saved: int,
        model_used: str,
        levels_applied: list[str],
        byok_provider: str | None = None,
    ) -> HandlerResult:
        cost_saved = tokens_saved * NOOR_COST_PER_TOKEN_USD
        # Persisting savings must never break the response.
        try:
            profile_store.record_request_savings(
                savings_id=str(uuid.uuid4()),
                user_id=user_id,
                conversation_id=conversation_id,
                tokens_saved=tokens_saved,
                cost_saved_usd=cost_saved,
                cache_hit=cache_hit,
                memories_used=memories_used,
            )
        except Exception as error:  # noqa: BLE001
            logger.warning("Recording request savings failed: %s", error)

        return HandlerResult(
            content=content,
            cache_result=(
                "OFF" if byok_provider else ("HIT" if cache_hit else "MISS")
            ),
            memories_used=memories_used,
            tokens_saved=tokens_saved,
            cost_saved_usd=cost_saved,
            model_used=model_used,
            levels_applied=levels_applied,
            byok_provider=byok_provider,
        )
